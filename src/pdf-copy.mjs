/* LiczMat website — the words on the PDF export, in ten languages.
 *
 * Session 59, the second half of item **C6** of the parity audit: "Eksport PDF i własne
 * materiały — tylko w aplikacji." The app has had `PdfConfigScreen` and
 * `AndroidProjectPdfExporter` since long before this site existed.
 *
 * **Every string here is the app's own**, copied out of `app/src/main/res/values-<lang>/strings.xml`
 * in `3d-polednia/Materio` — the `pdf_*` keys of the configurator and the `pdfdoc_*` keys of
 * the document. Nothing was invented and nothing was translated: one module may not be
 * called two different things on the two products, which is the rule session 53 wrote down
 * when the app took this site's `cal_*` strings, and session 57 followed the other way for
 * the converter. All ten languages already existed there, which is also why this half of
 * C6 needed no translator.
 *
 * It sits in src/ rather than in assets/i18n-pages.js for the reason src/conv-copy.mjs
 * does: every page on this site downloads assets/i18n.<lang>.js, and 51 keys per language
 * that only the build and a reader of a printed page ever see is about 3 kB on every page
 * load for nothing. The whole document is server-rendered into /projekty/ and hidden, and
 * the browser fills in numbers rather than words — so there is no runtime half at all.
 *
 * Three strings carry Android's `%1$s`. The build splits each one at the token and puts a
 * <span> the script fills between the halves, so the sentence keeps its word order in
 * every language — "Projekt: X" and "Проект: X" are not the same shape as a label glued
 * to a value, and neither is Romanian's.
 *
 * scripts/test-copy.mjs reads this file alongside the dictionaries, so the six stop-slop
 * rules cover it exactly as they cover everything else a visitor can read.
 */


/**
 * Android's `%1$s` split into the halves either side of it.
 *
 * "Projekt: %1$s" is a sentence with a hole in it, and the hole is not always at the end:
 * gluing a label to a value would put the Romanian and Ukrainian words in the wrong order.
 * The build writes `before` + a <span> the script fills + `after`.
 */
export function pdfSplit(text) {
  const i = String(text).indexOf("%1$s");
  if (i < 0) return { before: String(text), after: "" };
  return { before: String(text).slice(0, i), after: String(text).slice(i + 4) };
}

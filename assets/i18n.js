/** Translate a key for the active language, falling back to en → pl → the key itself. */
function t(key, lang) {
  const l = lang || document.documentElement.lang || "pl";
  return (I18N[l] && I18N[l][key]) || (I18N.en && I18N.en[key]) || (I18N.pl && I18N.pl[key]) || key;
}

/** Apply the chosen language to every [data-i18n] / [data-i18n-ph] node in the DOM. */
function applyLang(lang) {
  const l = I18N[lang] ? lang : "en";
  document.documentElement.lang = l;
  document.querySelectorAll("[data-i18n]").forEach((el) => { el.textContent = t(el.dataset.i18n, l); });
  document.querySelectorAll("[data-i18n-ph]").forEach((el) => { el.placeholder = t(el.dataset.i18nPh, l); });
  document.querySelectorAll("[data-i18n-alt]").forEach((el) => { el.alt = t(el.dataset.i18nAlt, l); });
  try { localStorage.setItem("materio-lang", l); } catch (e) {}
  document.dispatchEvent(new CustomEvent("langchange", { detail: { lang: l } }));
}

/** Best language on first visit: saved choice → browser language → Polish. */
function initialLang() {
  try { const saved = localStorage.getItem("materio-lang"); if (saved && I18N[saved]) return saved; } catch (e) {}
  const nav = (navigator.language || "pl").slice(0, 2).toLowerCase();
  return I18N[nav] ? nav : "pl";
}
